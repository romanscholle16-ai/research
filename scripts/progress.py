"""Honest progress scoreboard -> docs/PROGRESS.md (appends a dated snapshot; development-stage + aggregate outcomes only)."""
import json, time, os
import numpy as np
from pathlib import Path
from strategylab.db import DB

d = DB(); now = time.time(); H = 6 * 3600
def pct(a, b): return f"{100*a/b:.1f}%" if b else "n/a"
rows = d.q("SELECT stage,status,symbol,timeframe FROM experiments WHERE synthetic=0 AND timeframe!='4h' AND finished>?", (now - H,))
c = {}
for r in rows: c[(r["stage"], r["status"])] = c.get((r["stage"], r["status"]), 0) + 1
scr = c.get(("screen", "pass"), 0) + c.get(("screen", "fail"), 0); val = c.get(("validate", "pass"), 0) + c.get(("validate", "fail"), 0)
sur = d.q("SELECT COUNT(*) n FROM director_batches WHERE ts>?", (now - H,))[0]["n"]
ss = d.get("surrogate_stats") or {}
by = {}
for r in d.q("SELECT symbol,timeframe,stage,status FROM experiments WHERE synthetic=0 AND stage IN ('screen','validate') AND timeframe!='4h' AND finished>?", (now - H,)):
    k = (r["symbol"], r["timeframe"]); x = by.setdefault(k, [0, 0, 0]); x[0] += r["stage"] == "screen"; x[1] += r["stage"] == "screen" and r["status"] == "pass"; x[2] += r["stage"] == "validate" and r["status"] == "pass"
cnt = d.counts(0); fin = d.q("SELECT COUNT(*) n FROM experiments WHERE stage='final' AND synthetic=0 AND timeframe!='4h' AND finished>?", (now - H,))[0]["n"]
best = d.q("SELECT strategy_id,symbol,timeframe,status,summary_json FROM strategy_status WHERE synthetic=0 AND status IN ('BACKTEST_QUALIFIED','PAPER_VALIDATED','LIVE_ELIGIBLE')")
L = [f"\n## Snapshot {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())} (window: last 6h, non-4h)",
     f"- experiments total {cnt.get('experiments',0)}; qualified strategies: **{len(best)}**; locked-test candidates in window: {fin}",
     f"- screen pass rate {pct(c.get(('screen','pass'),0), scr)} ({scr} screened); validation pass rate {pct(c.get(('validate','pass'),0), val)} ({val} validated)",
     f"- surrogate (learns from rejects): holdout corr {ss.get('holdout_corr')}, top-decile hit {ss.get('top_decile_hit')} vs base {ss.get('base_hit')} (train-period net R > 0.05) on {ss.get('n')} past screens",
     "- per market/timeframe (screens / screen-pass / validate-pass): " + "; ".join(f"{k[0][:3]} {k[1]}: {v[0]}/{v[1]}/{v[2]}" for k, v in sorted(by.items()))]
p = Path("docs/PROGRESS.md")
if not p.exists(): p.write_text("# Research progress log (auto-generated by scripts/progress.py)\n")
p.write_text(p.read_text() + "\n".join(L) + "\n"); print("\n".join(L))
